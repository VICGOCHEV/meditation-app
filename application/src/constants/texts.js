// Подписи кнопок в CMS не редактируются — это элементы управления, а не текст.
export const DONATE_BANNER_SUPPORT_LABEL = 'Поддержать проект'
export const DONATE_BANNER_CONTINUE_LABEL = 'Продолжить путь'

/** Какой из четырёх вариантов финальной плашки показать. */
export function donateBannerText(texts, { donateAllowed, isLastInChain }) {
  if (donateAllowed) {
    return isLastInChain ? texts.donateBannerLast : texts.donateBanner
  }
  return isLastInChain ? texts.donateBannerVkLast : texts.donateBannerVk
}

