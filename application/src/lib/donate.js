import { isVkLaunch } from './vk'

// ─────────────────────────────────────────────────────────────────────────────
// ДОБРОВОЛЬНЫЙ ДОНАТ — решение клиента 2026-07-30 (docs/38).
//
// Форма приёма живёт ВНЕ приложения: отдельная страница /donate/ на домене
// проекта. Внутри приложения — только кнопка, которая её открывает.
//
// В VK Mini App кнопки нет вообще. Это не «отдельная механика для ВК» (доступ
// к практикам везде одинаковый), а требование площадки — письмо модерации ВК
// от 2026-07-30:
//   • п. 5.4.1 mini-apps-rules — на клиентах iOS/Android запрещены оплата,
//     уводы и подсказки, как и где можно оплатить, «даже в текстовом виде»;
//   • п. 5.4.2 — принимать оплату можно только одобренными ВК способами,
//     ЮKassa в их перечень не входит.
// Отличить внутри VK десктоп от мобильного клиента можно по vk_platform, но
// разрешённых способов оплаты у нас всё равно нет, поэтому проще и безопаснее
// не показывать донат ни в одном VK-запуске.
// ─────────────────────────────────────────────────────────────────────────────

export const DONATE_URL =
  import.meta.env.VITE_DONATE_URL || 'https://all-relaxme.ru/donate/'

/** Можно ли показывать кнопку доната в текущем окружении. */
export function isDonateAllowed() {
  return !isVkLaunch()
}

/**
 * Открыть страницу доната снаружи приложения.
 * В Telegram — через WebApp.openLink (иначе ссылка откроется внутри WebView
 * поверх мини-аппа), в остальных случаях обычным новым окном.
 */
export function openDonate() {
  if (!isDonateAllowed()) return
  try {
    const tg = window.Telegram?.WebApp
    if (tg?.openLink) {
      tg.openLink(DONATE_URL)
      return
    }
  } catch {
    /* падаем в обычный window.open */
  }
  window.open(DONATE_URL, '_blank', 'noopener,noreferrer')
}
