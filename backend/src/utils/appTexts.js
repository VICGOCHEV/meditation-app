export const APP_TEXT_NAMES = Object.keys(APP_TEXT_DEFAULTS)

/**
 * Накладывает сохранённые значения на дефолты.
 * @param {Array<{key:string, value:string}>} rows — строки AppSetting
 */
export function mergeTexts(rows) {
  const byKey = Object.fromEntries((rows || []).map((r) => [r.key, r.value]))
  const out = {}
  for (const name of APP_TEXT_NAMES) {
    const saved = byKey[APP_TEXT_KEYS[name]]
    // Пустая строка — валидное значение («ничего не показывать»), поэтому
    // проверяем именно на undefined, а не на truthy.
    out[name] = saved === undefined ? APP_TEXT_DEFAULTS[name] : saved
  }
  return out
}
