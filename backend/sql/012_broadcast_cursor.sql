-- Курсор пагинации для broadcast-воркера.
--
-- Раньше пачка получателей бралась через skip = sent_count + failed_count по
-- живой выборке. Если во время рассылки кто-то отписывался или подписывался,
-- окно сдвигалось: часть людей пропускалась, часть получала сообщение дважды.
-- Курсор по id получателя от этого не зависит.
--
-- Идемпотентно. Для идущих сейчас рассылок NULL означает «начать с начала» —
-- на практике на момент миграции незавершённых рассылок нет.

ALTER TABLE "BroadcastJob" ADD COLUMN IF NOT EXISTS "last_recipient_id" INTEGER;
